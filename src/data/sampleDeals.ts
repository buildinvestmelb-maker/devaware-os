function makeRectBoundary(
  lat: number,
  lng: number,
  dLat = 0.0014,
  dLng = 0.0022,
): FeatureCollection {
  return {
    type: 'FeatureCollection',
    features: [
      {
        type: 'Feature',
        properties: { role: 'parcel-boundary' },
        geometry: {
          type: 'Polygon',
          coordinates: [
            [
              [Number((lng - dLng).toFixed(6)), Number((lat - dLat).toFixed(6))],
              [Number((lng + dLng).toFixed(6)), Number((lat - dLat).toFixed(6))],
              [Number((lng + dLng).toFixed(6)), Number((lat + dLat).toFixed(6))],
              [Number((lng - dLng).toFixed(6)), Number((lat + dLat).toFixed(6))],
              [Number((lng - dLng).toFixed(6)), Number((lat - dLat).toFixed(6))],
            ],
          ],
        },
      },
    ],
  };
}

function buildLocation(
  state: AustralianState,
  address: string,
  lga: string,
  lat: number,
  lng: number,
) {
  const { mgaZone, mgaEpsg } = getMga2020FromLng(lng);
  return {
    address,
    lga,
    state,
    lat,
    lng,
    mgaZone,
    mgaEpsg,
  };
}

